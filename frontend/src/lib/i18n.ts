const DICTIONARIES: Record<Language, Dictionary> = { en, hi, hinglish };

/** The text for a key in a language (English when it has no translation). */
export function translate(lang: Language, key: MessageKey): string {
  return DICTIONARIES[lang][key] ?? en[key];
}

export const LANGUAGE_STORAGE_KEY = "croquis-language";

export function isLanguage(value: unknown): value is Language {
  return value === "en" || value === "hi" || value === "hinglish";
}
