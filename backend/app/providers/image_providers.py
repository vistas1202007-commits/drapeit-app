"""Real image-generation providers: Google Gemini ("Nano Banana") and OpenAI GPT Image.

Both take the same ImageRequest (a text prompt built from the design spec) and
return a PNG/JPEG picture. The generator then saves the picture as an asset
linked to the design version, so nothing is lost when the design changes.

Keys come from backend/.env (GEMINI_API_KEY / OPENAI_API_KEY). Prices below
are estimates for the spending limit only; check each company's pricing page.
"""

from __future__ import annotations

import base64
import logging

import httpx

from app.providers.base import GeneratedImage, ImageRequest, ProviderError, ProviderInfo, UsageMeter
from app.services.uploads import detect_image_type

log = logging.getLogger(__name__)

# Approximate US dollars per portrait image (October 2026 prices).
GEMINI_COST_PER_IMAGE = {"gemini-nano-banana-2.1": 0.035, "gemini-3.1-flash-lite-image": 0.035}
GEMINI_UNKNOWN_COST = 0.15
OPENAI_COST_PER_IMAGE = {"low": 0.01, "medium": 0.08, "high": 0.30}


def _check_image(data: bytes | None, provider: str) -> tuple[bytes, str]:
    if not data:
        raise ProviderError(f"{provider} returned no image. Try again or change the design text.")
    mime = detect_image_type(data)
    if mime is None:
        raise ProviderError(f"{provider} returned a file that is not a PNG, JPEG or WebP image.")
    return data, mime


class GeminiImageProvider:
    def __init__(self, api_key: str, model: str) -> None:
        from google import genai  # imported here so the app still starts if the package is missing

        self.client = genai.Client(api_key=api_key)
        self.model = model
        self.cost = GEMINI_COST_PER_IMAGE.get(model, GEMINI_UNKNOWN_COST)
        self.info = ProviderInfo(
            name=f"gemini ({model})", is_mock=False, paid=True, estimated_cost_usd=self.cost,
            note="Real AI: Google Gemini image generation. Costs money per image.",
        )

    def generate_image(self, request: ImageRequest, meter: UsageMeter) -> GeneratedImage:
        from google.genai import errors, types

        try:
            response = self.client.models.generate_content(
                model=self.model,
                contents=request.prompt,
                config=types.GenerateContentConfig(
                    response_modalities=["IMAGE"],
                    image_config=types.ImageConfig(aspect_ratio="2:3", image_size="1K"),
                ),
            )
        except errors.ClientError as exc:
            if exc.code in (401, 403) or "api key" in str(exc.message).lower():
                raise ProviderError("Gemini rejected the API key. Check GEMINI_API_KEY in backend/.env.") from exc
            if exc.code == 429:
                raise ProviderError("Gemini quota reached. Check billing is on, then wait a minute and retry.") from exc
            if exc.code == 404:
                raise ProviderError(f"Model '{self.model}' was not found. Check GEMINI_IMAGE_MODEL.") from exc
            raise ProviderError(f"Gemini could not accept the request: {exc.message}") from exc
        except errors.ServerError as exc:
            raise ProviderError(f"Gemini had a server problem ({exc.code}). Please retry.") from exc
        except (OSError, httpx.HTTPError) as exc:
            raise ProviderError("Could not connect to Gemini. Check your internet connection.") from exc

        meter.add(self.cost, f"gemini image ({self.model})")
        data = None
        for candidate in response.candidates or []:
            for part in (candidate.content.parts if candidate.content else None) or []:
                if part.inline_data and part.inline_data.data:
                    data = part.inline_data.data
                    break
            if data:
                break
        if data is None and response.prompt_feedback and response.prompt_feedback.block_reason:
            raise ProviderError("Gemini's safety filter blocked this picture. Try rewording the design.")
        data, mime = _check_image(data, "Gemini")
        return GeneratedImage(mime_type=mime, data=data, caption=f"Generated by Gemini ({self.model})")


class OpenAIImageProvider:
    def __init__(self, api_key: str, model: str, quality: str) -> None:
        import openai

        self.openai = openai
        self.client = openai.OpenAI(api_key=api_key, timeout=180.0, max_retries=1)
        self.model = model
        self.quality = quality if quality in OPENAI_COST_PER_IMAGE else "medium"
        self.cost = OPENAI_COST_PER_IMAGE[self.quality]
        self.info = ProviderInfo(
            name=f"openai ({model}, {self.quality})", is_mock=False, paid=True, estimated_cost_usd=self.cost,
            note="Real AI: OpenAI GPT Image. Costs money per image.",
        )

    def generate_image(self, request: ImageRequest, meter: UsageMeter) -> GeneratedImage:
        openai = self.openai
        try:
            result = self.client.images.generate(
                model=self.model, prompt=request.prompt, size="1024x1536", quality=self.quality, n=1,
            )
        except openai.AuthenticationError as exc:
            raise ProviderError("OpenAI rejected the API key. Check OPENAI_API_KEY in backend/.env.") from exc
        except openai.PermissionDeniedError as exc:
            raise ProviderError(
                "OpenAI says this account cannot use this image model yet (it may need organisation verification)."
            ) from exc
        except openai.RateLimitError as exc:
            raise ProviderError("OpenAI limit or credit reached. Check billing, then retry.") from exc
        except openai.BadRequestError as exc:
            raise ProviderError(f"OpenAI could not accept the request: {exc.message}") from exc
        except openai.APIConnectionError as exc:
            raise ProviderError("Could not connect to OpenAI. Check your internet connection.") from exc
        except openai.APIStatusError as exc:
            raise ProviderError(f"OpenAI had a server problem ({exc.status_code}). Please retry.") from exc

        meter.add(self.cost, f"openai image ({self.model}, {self.quality})")
        b64 = result.data[0].b64_json if result.data else None
        data, mime = _check_image(base64.b64decode(b64) if b64 else None, "OpenAI")
        return GeneratedImage(mime_type=mime, data=data, caption=f"Generated by OpenAI ({self.model})")
